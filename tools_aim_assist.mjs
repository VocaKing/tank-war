import assert from 'node:assert/strict';
import * as THREE from 'three';
import { AimDrag, AIM_DRAG } from './src/game/aimDrag.js';
import { AimAssist } from './src/game/aimAssist.js';
const d = new AimDrag();
assert.equal(d.factor(),0.18);
for (let i=0;i<20;i++) assert.equal(d.push(3,0,i*20).reason,null);
assert.ok(d.factor()<0.25);
d.reset();
for(let i=0;i<20;i++) assert.equal(d.push(i%2?12:-12,0,i*10).reason,null);
d.reset();
assert.equal(d.push(41,0,0).reason,null); assert.equal(d.push(41,0,50).reason,'flick');
d.reset();
let reason = null;
for(let i=0;i<100 && !reason;i++) reason=d.push(12,0,i*25).reason;
assert.equal(reason,'drag');
d.reset(); d.push(40,0,0); d.decay(2000); assert.ok(d.pressure<1);
// Integration state machine: exact same frame acquisition and outline, no re-anchor pressure reset.
const root=new THREE.Group(), turret=new THREE.Group(); root.add(turret);
const enemy={alive:true,team:1,spotted:[true,false],model:{root,turret}};
const player={alive:true,team:0};
const g={player,tanks:[player,enemy],time:0,lock:null,aimTank:enemy,aimHit:{part:'hull'},aimPoint:new THREE.Vector3(0,1,0),camera:{fov:60},cam:{yaw:0,pitch:0}};
const a=new AimAssist(g,true);
assert.equal(a.postAim(),true); assert.equal(a.target,enemy); assert.equal(a.outlineTarget(),enemy);
assert.equal(a.dragFactor(),AIM_DRAG.DRAG_MIN);
assert.deepEqual(a.look(10,0,0.0024),[0,0]);
const pressure=a.drag.pressure; a.postAim(); assert.equal(a.drag.pressure,pressure);
const result=a.look(90,0,0.0024); assert.ok(result[0]<-0.2); assert.equal(a.target,null); assert.equal(a.outlineTarget(),null);
assert.equal(a.postAim(),false); g.time=1; assert.equal(a.postAim(),false);
g.aimTank=null; a.postAim(); g.aimTank=enemy; assert.equal(a.postAim(),true);
enemy.spotted[0]=false; a.preCamera(); assert.equal(a.target,null); assert.equal(a.outlineTarget(),null);
enemy.spotted[0]=true; g.aimHit=null; assert.equal(a.postAim(),false);
g.aimHit={part:'hull'}; a.setEnabled(false); assert.equal(a.postAim(),false); assert.equal(a.outlineTarget(),null);
g.lock=enemy; a.postAim(); assert.equal(a.outlineTarget(),enemy);
console.log('Aim assist regression tests passed.');
