import { chromium } from 'playwright';
const [,, url, out, wait = '8000'] = process.argv;
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text().slice(0, 400)); });
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message + '\n' + (e.stack||'').slice(0,800)));
const t0 = Date.now();
await page.goto(url);
await page.waitForFunction(() => window.__game || document.querySelector('.loading pre'), null, { timeout: 120000 }).catch(e => errs.push('timeout waiting game'));
console.log('game ready after', Date.now() - t0, 'ms');
await page.waitForTimeout(+wait);
const info = await page.evaluate(() => window.__game ? { ...window.__game.debug.info(), fps: window.__fps } : document.querySelector('.loading')?.innerText);
console.log(JSON.stringify(info));
await page.screenshot({ path: out });
console.log(errs.slice(0, 30).join('\n') || 'no errors');
await browser.close();
