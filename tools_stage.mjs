import { chromium } from 'playwright';
const [url, out, code, wait = '8000', w = '1280', h = '720'] = process.argv.slice(2);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: +w, height: +h } });
const errs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
await page.goto(url);
await page.waitForFunction(() => window.__game, null, { timeout: 180000 });
const r = await page.evaluate(async (c) => { const g = window.__game; return await eval('(async()=>{' + c + '})()'); }, code || '');
if (r !== undefined) console.log('result:', JSON.stringify(r));
await page.waitForTimeout(+wait);
await page.screenshot({ path: out });
console.log('errors:', errs.length ? errs.join('\n') : 'none');
await browser.close();
